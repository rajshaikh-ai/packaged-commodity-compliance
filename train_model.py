"""
train_model.py
--------------
Creates the SYNTHETIC educational dataset (if it does not exist yet),
cleans it, trains three classifiers, compares them and saves the best one.

    python train_model.py              # train (creates dataset on first run)
    python train_model.py --regenerate # rebuild the synthetic dataset first

IMPORTANT: the dataset is synthetic. It is generated by the rule described in
`label_rule()` plus random label noise. The metrics therefore show how well a
model can learn that rule - they say nothing about real-world regulatory
accuracy.
"""

from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path

import joblib
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, precision_score, recall_score
from sklearn.model_selection import StratifiedKFold, cross_val_score, train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.tree import DecisionTreeClassifier

from feature_extractor import FEATURE_COLUMNS, REQUIRED_FIELDS

SEED = 42
ROOT = Path(__file__).parent
DATASET = ROOT / "dataset" / "product_labels.csv"
MODEL_PATH = ROOT / "models" / "compliance_model.pkl"
METRICS_PATH = ROOT / "evaluation" / "metrics.json"
CM_PATH = ROOT / "evaluation" / "confusion_matrix.png"

LABELS = {0: "compliant", 1: "non_compliant"}   # positive class = non-compliant


# ---------------------------------------------------------------------------
# 1. Synthetic dataset
# ---------------------------------------------------------------------------
def label_rule(row: dict) -> int:
    """The labelling rule used to create the synthetic data (1 = non-compliant).

    A label is non-compliant when the product is expired, when a core
    declaration (MRP, net quantity, date) is missing, or when fewer than
    two-thirds of the six checked declarations are present.
    """
    core_missing = not (row["mrp_present"] and row["quantity_present"] and row["date_present"])
    return int(row["is_expired"] == 1 or core_missing or row["label_completeness"] < 0.66)


def generate_synthetic_dataset(n_per_class: int = 250, noise: float = 0.05, seed: int = SEED) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    rows = {0: [], 1: []}
    while min(len(rows[0]), len(rows[1])) < n_per_class:
        # Three "label quality" profiles: well printed, partly readable, poor.
        p = rng.choice([0.95, 0.75, 0.45], p=[0.45, 0.35, 0.20])
        row = {f: int(rng.random() < p) for f in REQUIRED_FIELDS}
        row["expiry_detected"] = int(rng.random() < 0.5)
        if row["expiry_detected"]:
            row["date_present"] = 1                   # an expiry date is a date
        row["is_expired"] = int(row["expiry_detected"] and rng.random() < 0.3)
        row["label_completeness"] = round(sum(row[f] for f in REQUIRED_FIELDS) / 6, 3)
        y = label_rule(row)
        if rng.random() < noise:                      # simulate human labelling mistakes
            y = 1 - y
        if len(rows[y]) < n_per_class:
            rows[y].append({**row, "label": LABELS[y]})

    df = pd.DataFrame(rows[0] + rows[1]).sample(frac=1, random_state=seed).reset_index(drop=True)

    # Make the raw file realistically messy so the cleaning step has work to do.
    for col in rng.choice(REQUIRED_FIELDS, size=12):
        df.loc[rng.integers(0, len(df)), col] = np.nan
    df.insert(0, "record_id", [f"SYN-{i:04d}" for i in range(1, len(df) + 1)])
    df["source"] = "synthetic"
    # 10 records accidentally entered twice (same record_id).
    df = pd.concat([df, df.sample(10, random_state=seed)], ignore_index=True)
    return df


# ---------------------------------------------------------------------------
# 2. Cleaning + feature preparation
# ---------------------------------------------------------------------------
def clean_dataset(df: pd.DataFrame) -> tuple[pd.DataFrame, dict]:
    report = {"raw_rows": len(df)}
    # Different products can legitimately share the same feature values, so
    # duplicates are detected by record_id (the same record entered twice).
    df = df.drop_duplicates(subset="record_id").drop(columns=["record_id"])
    report["duplicates_removed"] = report["raw_rows"] - len(df)
    before = len(df)
    df = df.dropna(subset=FEATURE_COLUMNS + ["label"])
    report["rows_with_missing_values_removed"] = before - len(df)
    df[REQUIRED_FIELDS + ["expiry_detected", "is_expired"]] = df[
        REQUIRED_FIELDS + ["expiry_detected", "is_expired"]].astype(int)
    # Recompute completeness so it always agrees with the six flags.
    df["label_completeness"] = (df[REQUIRED_FIELDS].sum(axis=1) / 6).round(3)
    df = df[df["label"].isin(LABELS.values())]
    report["clean_rows"] = len(df)
    report["class_counts"] = df["label"].value_counts().to_dict()
    return df.reset_index(drop=True), report


# ---------------------------------------------------------------------------
# 3. Training, comparison, evaluation
# ---------------------------------------------------------------------------
def candidate_models() -> dict:
    return {
        "Logistic Regression": make_pipeline(StandardScaler(), LogisticRegression(max_iter=1000, random_state=SEED)),
        "Decision Tree": DecisionTreeClassifier(max_depth=5, min_samples_leaf=4, random_state=SEED),
        "Random Forest": RandomForestClassifier(n_estimators=200, max_depth=6, min_samples_leaf=2, random_state=SEED),
    }


def evaluate(y_true, y_pred) -> dict:
    return {
        "accuracy": round(accuracy_score(y_true, y_pred), 4),
        "precision": round(precision_score(y_true, y_pred, zero_division=0), 4),
        "recall": round(recall_score(y_true, y_pred, zero_division=0), 4),
        "f1": round(f1_score(y_true, y_pred, zero_division=0), 4),
    }


def plot_confusion_matrix(cm: np.ndarray, title: str, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(4.2, 3.6), dpi=160)
    ax.imshow(cm, cmap="Blues", vmin=0)
    names = ["Compliant", "Non-compliant"]
    ax.set_xticks([0, 1], names, fontsize=9, color="#1E2A44")
    ax.set_yticks([0, 1], names, fontsize=9, color="#1E2A44")
    ax.set_xlabel("Predicted", fontsize=9, color="#5B6478")
    ax.set_ylabel("Actual", fontsize=9, color="#5B6478")
    for i in range(2):
        for j in range(2):
            ax.text(j, i, cm[i, j], ha="center", va="center", fontsize=14, fontweight="bold",
                    color="white" if cm[i, j] > cm.max() / 2 else "#1E2A44")
    ax.set_title(title, fontsize=10, color="#1E2A44", pad=10)
    for spine in ax.spines.values():
        spine.set_visible(False)
    ax.tick_params(length=0)
    fig.tight_layout()
    fig.savefig(path, transparent=False, facecolor="white")
    plt.close(fig)


def main(regenerate: bool = False) -> None:
    for folder in (DATASET.parent, MODEL_PATH.parent, METRICS_PATH.parent):
        folder.mkdir(parents=True, exist_ok=True)

    # 1. Load (or create) the dataset
    if regenerate or not DATASET.exists():
        generate_synthetic_dataset().to_csv(DATASET, index=False)
        print(f"[data] Synthetic dataset written to {DATASET}")
    raw = pd.read_csv(DATASET)

    # 2. Clean
    df, cleaning = clean_dataset(raw)
    print(f"[clean] {cleaning}")

    # 3. Features / target
    X = df[FEATURE_COLUMNS]
    y = (df["label"] == "non_compliant").astype(int)

    # 4. Split
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.25, stratify=y, random_state=SEED)

    # 5. Train + compare (5-fold CV F1 on the training set decides the winner)
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    results, fitted = {}, {}
    for name, model in candidate_models().items():
        cv_f1 = cross_val_score(model, X_train, y_train, cv=cv, scoring="f1")
        model.fit(X_train, y_train)
        y_pred = model.predict(X_test)
        results[name] = {**evaluate(y_test, y_pred), "cv_f1_mean": round(cv_f1.mean(), 4),
                         "cv_f1_std": round(cv_f1.std(), 4),
                         "confusion_matrix": confusion_matrix(y_test, y_pred).tolist()}
        fitted[name] = model
        print(f"[model] {name:20s} test F1={results[name]['f1']:.3f}  CV F1={cv_f1.mean():.3f} Â+/- {cv_f1.std():.3f}")

    best_name = max(results, key=lambda n: results[n]["cv_f1_mean"])   # ties -> first (simplest)
    best = fitted[best_name]
    print(f"[select] Best model by cross-validated F1: {best_name}")

    # 6. Save model + evaluation artefacts
    joblib.dump({"model": best, "model_name": best_name, "features": FEATURE_COLUMNS,
                 "positive_class": "non_compliant", "seed": SEED}, MODEL_PATH)
    plot_confusion_matrix(np.array(results[best_name]["confusion_matrix"]),
                          f"{best_name} â€” test set (n={len(y_test)})", CM_PATH)

    importances = None
    if hasattr(best, "feature_importances_"):
        importances = dict(zip(FEATURE_COLUMNS, np.round(best.feature_importances_, 4).tolist()))

    METRICS_PATH.write_text(json.dumps({
        "best_model": best_name,
        "selection_metric": "5-fold cross-validated F1 (training set)",
        "positive_class": "non_compliant",
        "test_size": len(y_test),
        "train_size": len(y_train),
        "cleaning": cleaning,
        "models": results,
        "feature_importances": importances,
        "trained_at": datetime.now().isoformat(timespec="seconds"),
        "disclaimer": "Synthetic educational dataset. Metrics do not represent real-world performance.",
    }, indent=2))
    print(f"[save] {MODEL_PATH.name}, {CM_PATH.name}, {METRICS_PATH.name}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Train the label compliance classifier.")
    parser.add_argument("--regenerate", action="store_true", help="rebuild the synthetic dataset")
    main(parser.parse_args().regenerate)

